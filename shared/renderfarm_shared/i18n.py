TRANSLATIONS = {"pt": PT, "es": ES}
LEGACY_ALIASES = {}
for _legacy, (_en, _pt, _es) in SERVICE_MESSAGES.items():
    LEGACY_ALIASES[_legacy] = _en
    PT[_en], ES[_en] = _pt, _es


def normalize_language(value: object, default: str = "en") -> str:
    normalized = str(value or "").strip().lower().replace("_", "-")
    if normalized.startswith("pt"):
        return "pt"
    if normalized.startswith("es"):
        return "es"
    if normalized.startswith("en"):
        return "en"
    return default if default in SUPPORTED_LANGUAGES else "en"


def tr(text: str, language: object = "en", **values: Any) -> str:
    language_code = normalize_language(language)
    text = LEGACY_ALIASES.get(text, text)
    translated = TRANSLATIONS.get(language_code, {}).get(text, text)
    if values:
        try:
            return translated.format(**values)
        except (KeyError, ValueError):
            return translated
    return translated


def translate_message(message: object, language: object = "en") -> str:
    """Translate known service messages while preserving unknown diagnostic details."""
    code = normalize_language(language)
    result = []
    for line in str(message).split("\n"):
        if line in LEGACY_ALIASES or line in PT or line in ES:
            result.append(tr(line, code))
            continue
        for template, translations in MESSAGE_PATTERNS.items():
            pattern = re.escape(template)
            pattern = re.sub(r"\\\{(\w+)\\\}", lambda match: f"(?P<{match[1]}>.+)", pattern)
            match = re.fullmatch(pattern, line)
            if match:
                result.append(translations[("en", "pt", "es").index(code)].format(**match.groupdict()))
                break
        else:
            result.append(line)
    return "\n".join(result)
